/** Replace owned URL rules, retaining the host's other rules and comments. */
export function replaceHeaderBlocks(existing: string, generated: string, paths: readonly string[]): string {
  const owned = new Set(paths);
  const lines: string[] = [];
  let skip = false;
  for (const line of existing.split('\n')) {
    if (line.startsWith('/') || /^https?:\/\//.test(line)) skip = owned.has(line.trim());
    if (line.startsWith('# Rayner explainers: generated by')) continue;
    if (!skip || line.startsWith('#')) lines.push(line);
  }
  return lines.join('\n').trimEnd() + '\n\n' + generated;
}
