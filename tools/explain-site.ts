#!/usr/bin/env node
// Copy the built collection into a static site, with the response headers it needs.
//   npm run demos:build && npm run site:export -- <site-root> [--path /projects/rayner]
// Writes <site-root><path>/{<id>.html, <id>.png, <id>.mp4, <id>.vtt, loader.js}, and the `_headers`
// block for those files to out/site-headers.txt (each page's CSP pins its own inline script and style).
import { copyFile, mkdir, readFile, writeFile, access } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { EXPLAINERS } from '../scenes/explainers/catalog.ts';
import { ROOT } from './lib/explain-project.ts';

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { path: { type: 'string', default: '/projects/rayner' } },
});
const root = positionals[0];
if (!root) throw new Error('usage: npm run site:export -- <site-root> [--path /projects/rayner]');
const path = values.path.replace(/\/$/, '');
const target = join(resolve(root), path);
const built = join(ROOT, 'out/explainers'),
  videos = join(ROOT, 'out/videos');
const exists = (file: string) => access(file).then(() => true, () => false);

await mkdir(target, { recursive: true });
const blocks: string[] = [];
for (const { id, video } of EXPLAINERS) {
  const page = join(built, id + '.html');
  if (!(await exists(page))) throw new Error(`Missing ${page}: run npm run demos:build first`);
  await copyFile(page, join(target, id + '.html'));
  await copyFile(join(built, id + '.png'), join(target, id + '.png'));
  for (const ext of video === false ? [] : ['.mp4', '.vtt']) if (await exists(join(videos, id + ext))) await copyFile(join(videos, id + ext), join(target, id + ext));
  const headers = JSON.parse(await readFile(join(built, id + '.html.headers.json'), 'utf8')) as Record<string, string>;
  const lines = Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`).join('\n');
  // The host serves /x.html at /x, so the rule covers both spellings.
  blocks.push(`${path}/${id}\n${lines}\n\n${path}/${id}.html\n${lines}`);
}
await copyFile(join(built, 'loader.js'), join(target, 'loader.js'));
const headers = `# Rayner explainers: generated by \`npm run site:export\`; regenerate rather than edit.\n${blocks.join('\n\n')}\n`;
const headersFile = join(ROOT, 'out/site-headers.txt');
await writeFile(headersFile, headers);
console.log(`Exported ${EXPLAINERS.length} explainers to ${target}\nAppend ${headersFile} to the site's _headers.`);
