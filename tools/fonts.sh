#!/usr/bin/env bash
# Regenerate src/font-data.ts: Inter and JetBrains Mono (OFL), subset to what
# diagrams of code use: Latin-1, general punctuation, arrows, math operators,
# geometric shapes and check marks. Needs fonttools + brotli:
#   pip install fonttools brotli && npm run fonts
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
(cd "$tmp" && npm pack --silent inter-ui@4.1.1 jetbrains-mono@1.0.6 >/dev/null && for t in *.tgz; do mkdir "${t%.tgz}" && tar xzf "$t" -C "${t%.tgz}"; done)
U="U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2190-21FF,U+2200-22FF,U+2300-23FF,U+25A0-25FF,U+2713,U+2717"
# Code is shown as literal source (as in a diff), so the mono face keeps no
# ligature lookups: `->` stays two characters, and shaping stays cheap.
sub() { pyftsubset "$1" --unicodes="$U" --layout-features="$3" --flavor=woff2 --output-file="$2"; }
sub "$tmp/inter-ui-4.1.1/package/web/Inter-Regular.woff2" "$tmp/sans.woff2" 'kern,liga,ccmp,locl,mark,mkmk'
sub "$tmp/jetbrains-mono-1.0.6/package/fonts/webfonts/JetBrainsMono-Regular.woff2" "$tmp/mono.woff2" 'kern,mark,mkmk'
{
  echo "// Generated by tools/fonts.sh: Inter 4.1 and JetBrains Mono 2.242 (OFL), WOFF2, base64. Do not edit."
  for k in sans mono; do echo "export const ${k^^}: string = '$(base64 -w0 "$tmp/$k.woff2")';"; done
} > src/font-data.ts
ls -l "$tmp"/*.woff2 | awk '{print $5, $9}'
